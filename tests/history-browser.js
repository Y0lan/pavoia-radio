async page => {
  const assert=(ok,message)=>{if(!ok)throw new Error(message);};
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const origin=new URL(page.url()).origin;
  await page.goto(origin+'/');
  await page.waitForFunction(()=>window.Pavoia?.stations?.length===9);
  assert(await page.locator('#bus-link').evaluate(n=>n===n.parentElement.lastElementChild),'Bus must remain last');
  await page.locator('#audio').evaluate(a=>{a.volume=0;});
  await page.locator('#play').click();
  await page.waitForFunction(()=>window.Pavoia.getState().playbackState==='playing');
  const source=await page.locator('#audio').getAttribute('src');
  await page.locator('#go-deeper').click();
  await page.locator('.explorer-nav a[href="#history"]').click();
  await page.waitForFunction(()=>document.querySelectorAll('.history-row').length===50);
  assert(await page.locator('#history-period').inputValue()==='7','Wrong default history period');
  const first=await page.locator('.history-row').first().textContent();
  await page.locator('#history-more').click();
  await page.waitForFunction(()=>document.querySelectorAll('.history-row').length===100);
  assert(await page.locator('.history-row').first().textContent()===first,'Older records replaced recent records');
  await page.locator('#history-period').selectOption('1');
  await page.waitForFunction(()=>document.querySelectorAll('.history-row').length===50);
  await page.locator('#music-stage').selectOption('ambiance');
  await page.waitForFunction(()=>document.querySelector('.history-row small')?.textContent==='Ambiance');
  const row=page.locator('.history-row').first();await row.click();
  await page.waitForFunction(()=>!document.getElementById('explore-workspace').hidden);
  await page.goBack();
  await page.waitForFunction(()=>document.querySelectorAll('.history-row').length===50&&!document.getElementById('music-view').hidden);
  assert(await page.locator('#music-stage').inputValue()==='ambiance','Back lost the selected history stage');
  await page.locator('.explorer-nav a[href="#statistics"]').click();
  await page.waitForFunction(()=>document.querySelector('.music-summary'));
  assert(Number((await page.locator('.music-summary dd').first().innerText()).replaceAll(',',''))>0,'Missing stage statistics');
  await page.locator('#music-stage').selectOption('radio');
  await page.waitForFunction(()=>document.querySelector('.music-summary dd')&&document.getElementById('music-status').textContent==='');
  await page.locator('#music-stage').selectOption('fontanna');
  await page.waitForFunction(()=>document.querySelector('.music-summary')&&document.getElementById('music-status').textContent==='');
  assert((await page.locator('#music-content').innerText()).includes('Shared with other stages'),'Overlap chart missing');
  for(const width of [1440,390,320]){
    await page.setViewportSize({width,height:width===1440?1000:844});
    assert(await page.locator('#explorer').evaluate(n=>n.scrollWidth<=n.clientWidth+1),'Statistics overflow '+width);
    await page.screenshot({path:'output/playwright/music-statistics-'+width+'.png'});
  }
  assert(await page.locator('#audio').getAttribute('src')===source&&await page.locator('#audio').evaluate(a=>!a.paused),'Browsing stopped the radio');
  await page.locator('.explorer-nav a[href="#history"]').click();
  await page.waitForFunction(()=>document.querySelectorAll('.history-row').length===50);
  assert(await page.locator('#explorer').evaluate(n=>n.scrollWidth<=n.clientWidth+1),'History overflow');
  await page.screenshot({path:'output/playwright/music-history-320.png'});
  await page.route('**/api/radio/fontanna/history?**',r=>r.fulfill({status:503,body:'unavailable'}));
  await page.locator('#history-period').selectOption('30');
  await page.getByRole('button',{name:'Try again',exact:true}).waitFor();
  assert(await page.locator('.history-row').count()===0,'Failed request retained misleading rows');
  await page.unroute('**/api/radio/fontanna/history?**');
  await page.getByRole('button',{name:'Try again',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.history-row').length===50);
  await page.locator('#explorer-close').click();
  await page.locator('#language').selectOption('de');
  await page.locator('#go-deeper').click();
  await page.locator('.explorer-nav a[href="#statistics"]').click();
  await page.waitForFunction(()=>document.querySelector('.music-summary'));
  assert(await page.locator('#explorer-title').innerText()==='Musikstatistik','Statistics heading not translated');
  await page.screenshot({path:'output/playwright/music-statistics-de-320.png'});
  await page.keyboard.press('Escape');
  await page.locator('#language').selectOption('en');
  await page.locator('#play').click();
  assert(errors.length===0,errors.join('; '));
  return {stations:9,historyPagination:true,period:true,entityNavigation:true,retry:true,statistics:true,mobile:true,languages:['en','de'],playbackPreserved:true,errors};
}
